    // ---- 构建 ----

    private class IconPath(val d: String, val evenOdd: Boolean = false)

    private fun icon(
        name: String,
        autoMirror: Boolean = false,
        evenOdd: Boolean = false,
        d: String
    ): ImageVector = icon(name, autoMirror, listOf(IconPath(d, evenOdd)))

    private fun icon(
        name: String,
        autoMirror: Boolean = false,
        paths: List<IconPath>
    ): ImageVector = ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 24f,
        viewportHeight = 24f,
        autoMirror = autoMirror
    ).apply {
        paths.forEach { p ->
            addPath(
                pathData = PathParser().parsePathString(p.d).toNodes(),
                pathFillType = if (p.evenOdd) PathFillType.EvenOdd else PathFillType.NonZero,
                fill = SolidColor(Color.Black)
            )
        }
    }.build()
